export async function initAudio() {
  const AudioCtx = globalThis.AudioContext || globalThis.webkitAudioContext;
  let ctx = null;
  let masterGain = null;
  let sfxGain = null;
  let musicGain = null;
  let musicOsc = null;
  let ambienceSrc = null;
  let ambienceGain = null;
  let ambienceFilter = null;
  let ambienceLfo = null;
  let masterVol = 0.8;
  let sfxVol = 1.0;
  let musicVol = 0.6;
  const buffers = new Map();
  let loadPromise = null;

  function ensureContext() {
    if (!ctx && AudioCtx) {
      try {
        ctx = new AudioCtx();
        masterGain = ctx.createGain();
        sfxGain = ctx.createGain();
        musicGain = ctx.createGain();
        masterGain.gain.value = masterVol;
        sfxGain.gain.value = sfxVol;
        musicGain.gain.value = musicVol * 0.12;
        sfxGain.connect(masterGain);
        musicGain.connect(masterGain);
        masterGain.connect(ctx.destination);
      } catch (_) {
        ctx = null;
      }
    }
    return ctx;
  }

  async function loadSamples() {
    const c = ensureContext();
    if (!c) return buffers.size;
    const jobs = Object.entries(SAMPLE_MAP).map(async ([key, url]) => {
      try {
        const res = await fetch(url, { cache: "force-cache" });
        if (!res.ok) return;
        const data = await res.arrayBuffer();
        const buf = await c.decodeAudioData(data);
        buffers.set(key, buf);
      } catch (_) { /* fall back to the synth for this key */ }
    });
    await Promise.all(jobs);
    return buffers.size;
  }

  function playSample(key, options = {}) {
    const c = ensureContext();
    const buf = buffers.get(key);
    if (!c || !buf) return false;
    try {
      const src = c.createBufferSource();
      src.buffer = buf;
      const g = c.createGain();
      const vol = Math.max(0, Math.min(1, options.volume ?? 1)) * 0.85;
      const pitch = Math.max(0.4, Math.min(2.4, options.pitch ?? 1));
      src.playbackRate.value = pitch;
      const t0 = c.currentTime + (options.delay || 0);
      g.gain.setValueAtTime(0.0001, t0);
      g.gain.exponentialRampToValueAtTime(Math.max(0.0002, vol), t0 + 0.008);
      g.gain.exponentialRampToValueAtTime(0.0001, t0 + Math.min(1.4, buf.duration / pitch));
      src.connect(g); g.connect(sfxGain);
      src.start(t0);
      src.stop(t0 + Math.min(1.5, buf.duration / pitch) + 0.02);
      return true;
    } catch (_) { return false; }
  }

  const controller = {
    playSfx(key, options = {}) {
      const c = ensureContext();
      if (playSample(key, options)) return true;      // real sample first
      return createSynthSfx(c, masterGain, sfxGain, key, options);
    },
    playMusic(key, options = {}) {
      const c = ensureContext();
      if (!c) return;
      controller.stopMusic();
      // No music bed. A bare 48-64 Hz sine/sawtooth read as an electrical hum, not atmosphere, and
      // it ran under everything. Silence is better than a buzz; the SFX carry the scene.
      musicOsc = null;
    },
    /**
     * Rain/wind bed. The sample file was never shipped, so this synthesises its own loop: two
     * decorrelated pink-noise channels (rain hiss) with a slow wind LFO on the lowpass. No asset,
     * seamless, and it fades instead of popping.
     */
    async startAmbience(volume = 0.1) {
      const c = ensureContext();
      if (!c) return;
      if (ambienceSrc) {
        // already running: just bring it back up if a previous run faded it out
        try {
          ambienceGain.gain.cancelScheduledValues(c.currentTime);
          ambienceGain.gain.setValueAtTime(ambienceGain.gain.value, c.currentTime);
          ambienceGain.gain.linearRampToValueAtTime(Math.max(0.0001, Math.min(0.3, volume)), c.currentTime + 1.6);
        } catch (_) {}
        return;
      }
      try {
        const seconds = 8;
        const rate = c.sampleRate;
        const buf = c.createBuffer(2, Math.floor(rate * seconds), rate);
        for (let ch = 0; ch < 2; ch += 1) {
          const data = buf.getChannelData(ch);
          // pink-ish noise: leaky integration of white noise, then a soft hiss layer
          let b0 = 0, b1 = 0, b2 = 0;
          let seed = 12345 + ch * 777;
          for (let i = 0; i < data.length; i += 1) {
            seed = (seed * 1664525 + 1013904223) >>> 0;
            const white = (seed / 4294967296) * 2 - 1;
            b0 = 0.99765 * b0 + white * 0.0990460;
            b1 = 0.96300 * b1 + white * 0.2965164;
            b2 = 0.57000 * b2 + white * 1.0526913;
            const pink = (b0 + b1 + b2 + white * 0.1848) * 0.12;
            data[i] = pink;
          }
          // crossfade the tail into the head so the loop point is inaudible
          const fade = Math.floor(rate * 0.6);
          for (let i = 0; i < fade; i += 1) {
            const k = i / fade;
            data[i] = data[i] * k + data[data.length - fade + i] * (1 - k);
          }
        }
        buffers.set("ambience", buf);
        ambienceSrc = c.createBufferSource();
        ambienceSrc.buffer = buf;
        ambienceSrc.loop = true;
        ambienceFilter = c.createBiquadFilter();
        ambienceFilter.type = "lowpass";
        ambienceFilter.frequency.value = 1150;
        ambienceFilter.Q.value = 0.6;
        // wind: slow LFO breathing the filter cutoff (+/- 220 Hz over ~17 s)
        const lfo = c.createOscillator();
        lfo.frequency.value = 0.06;
        const lfoGain = c.createGain();
        lfoGain.gain.value = 220;
        lfo.connect(lfoGain).connect(ambienceFilter.frequency);
        lfo.start();
        ambienceGain = c.createGain();
        ambienceGain.gain.value = 0.0001;
        ambienceSrc.connect(ambienceFilter).connect(ambienceGain).connect(masterGain);
        ambienceSrc.start();
        ambienceGain.gain.exponentialRampToValueAtTime(Math.max(0.0002, Math.min(0.3, volume)), c.currentTime + 2.4);
        ambienceLfo = lfo;
      } catch (_) {
        ambienceSrc = null;
      }
    },
    stopAmbience(fade = 1.4) {
      const c = ctx;
      if (!c || !ambienceSrc) return;
      try {
        const now = c.currentTime;
        ambienceGain.gain.cancelScheduledValues(now);
        ambienceGain.gain.setValueAtTime(Math.max(0.0001, ambienceGain.gain.value), now);
        ambienceGain.gain.exponentialRampToValueAtTime(0.0001, now + fade);
        const src = ambienceSrc;
        const lfo = ambienceLfo;
        setTimeout(() => {
          try { src.stop(); src.disconnect(); } catch (_) {}
          try { if (lfo) { lfo.stop(); lfo.disconnect(); } } catch (_) {}
        }, Math.ceil(fade * 1000) + 60);
      } catch (_) {
        try { ambienceSrc.stop(); } catch (_) {}
      }
      ambienceSrc = null;
      ambienceGain = null;
      ambienceFilter = null;
      ambienceLfo = null;
    },
    ambienceActive() {
      return Boolean(ambienceSrc);
    },
    contextState() {
      return ctx ? ctx.state : "none";
    },
    stopMusic() {
      if (musicOsc) {
        try { musicOsc.stop(); musicOsc.disconnect(); } catch (_) {}
        musicOsc = null;
      }
    },
    setMasterVolume(v) {
      masterVol = Math.max(0, Math.min(1, Number(v) || 0));
      if (masterGain) masterGain.gain.value = masterVol;
    },
    setSfxVolume(v) {
      sfxVol = Math.max(0, Math.min(1, Number(v) || 0));
      if (sfxGain) sfxGain.gain.value = sfxVol;
    },
    setMusicVolume(v) {
      musicVol = Math.max(0, Math.min(1, Number(v) || 0));
      if (musicGain) musicGain.gain.value = musicVol * 0.12;
    },
    async preload() {
      if (!loadPromise) loadPromise = loadSamples();
      await loadPromise;
      return buffers.size;
    },
    sampleCount() { return buffers.size; },
    sampleKeys() { return [...buffers.keys()]; },
    suspend() {
      if (ctx && ctx.state === "running") {
        try { return ctx.suspend(); } catch (_) {}
      }
    },
    resume() {
      const c = ensureContext();
      if (c && c.state === "suspended") {
        try { return c.resume(); } catch (_) {}
      }
    },
    destroy() {
      controller.stopMusic();
      controller.stopAmbience(0.2);
      if (ctx) {
        try { ctx.close(); } catch (_) {}
        ctx = null;
      }
    },
  };
  return controller;
}

export function playSfx(audio, key, options = {}) {
  if (audio && typeof audio.playSfx === "function") {
    // Apply +/-6% pitch variation for weapon reports
    const pitchVariation = 1 + (Math.random() - 0.5) * 0.12; // 0.94 to 1.06
    const opts = { ...options, pitch: (options.pitch || 1) * pitchVariation };
    return audio.playSfx(key, opts);
  }
  return { playing: false, stop() {}, setVolume() {}, setPitch() {} };
}

export function playMusic(audio, key, options = {}) {
  if (audio && typeof audio.playMusic === "function") {
    return audio.playMusic(key, options);
  }
}

